// Derive ID translation from the bounded native switch disassembly/table.
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url),read=p=>readFileSync(new URL(p,root),'utf8');
const table=read('backups/animations/live-native-script-animation-switch-table.txt').trim().split(': ')[1].split(', ');
const assembly=read('backups/animations/live-native-wait-animation-full-asm.txt');
const map=table.map((rva,id)=>{
  if(id===112||id===113)return null; // active appearance MODELTYPE lookup.
  const instruction=assembly.split(`140${rva}: `)[1]?.split('\n')[0].trim();
  if(instruction==='mov dword ptr [rbp - 0x18], edi')return 0;
  const immediate=instruction?.match(/^mov dword ptr \[rbp - 0x18\], (0x[0-9a-f]+|[0-9]+)$/);
  if(!immediate)throw new Error(`Unmapped native script animation${id}: ${instruction}`);
  return Number(immediate[1]);
});
if(map.length!==117)throw new Error('Native animation switch table length changed');
writeFileSync(new URL('src/script_animation_map.js',root),`// ExecuteCommandPlayAnimation140538060, switch table140538ba0.\n// Generated by scripts/generate-script-animation-map.mjs; null uses MODELTYPE.\nexport const scriptAnimationMap=${JSON.stringify(map)};\n`);
