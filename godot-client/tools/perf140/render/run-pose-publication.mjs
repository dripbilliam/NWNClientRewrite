import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const id = process.argv[2];
if (!/^[a-z0-9-]+$/i.test(id ?? '')) throw Error('Private candidate identifier required');
const stage = path.join(project, '.cache/native-140fps/render-agent', id);
const manifestFile = path.join(stage, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestFile));
if (manifest.builds !== 1 || !manifest.build) throw Error('Private build is not finalized');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
for (const pin of manifest.pins) if (hash(fs.readFileSync(path.join(manifest.project, pin.relative))) !== pin.sha256) throw Error('Private source drift: ' + pin.relative);
const originalResources = process.argv.includes('--resources');
const suffix = (originalResources ? 'resources-' : 'oracle-') + Date.now();
const directory = path.join(stage, suffix);
fs.mkdirSync(directory);
const engine = path.join(project, '.tools/Godot_v4.7.2-stable_win64.exe');
const nativeFile = path.join(directory, 'native.json');
const script = originalResources ? 'res://tests/native_perf140_render_pose_publication_resources_test.gd' : 'res://tests/native_perf140_render_pose_publication_test.gd';
const args = ['--headless', '--path', manifest.project, '--log-file', path.join(directory, 'engine.log'), '--script', script, '--', `--report=${nativeFile}`];
if (originalResources) args.push('--install=C:/Users/Niflheim/Desktop/Tools/Local Tools/FullDecomp/NwnRootInstall');
fs.writeFileSync(path.join(directory, 'invocation.json'), JSON.stringify({engine, engineSha256: hash(fs.readFileSync(engine)), args, manifestSha256: hash(fs.readFileSync(manifestFile)), gpu: false, serverConnections: 0}, null, 2), {flag: 'wx'});
const result = spawnSync(engine, args, {encoding: 'utf8', windowsHide: true, maxBuffer: 16 * 1024 * 1024, timeout: originalResources ? 120000 : 60000});
fs.writeFileSync(path.join(directory, 'stdout.log'), result.stdout ?? '', {flag: 'wx'});
fs.writeFileSync(path.join(directory, 'stderr.log'), result.stderr ?? '', {flag: 'wx'});
const native = fs.existsSync(nativeFile) ? JSON.parse(fs.readFileSync(nativeFile)) : null;
const text = (result.stdout ?? '') + '\n' + (result.stderr ?? '') + '\n' + (fs.existsSync(path.join(directory, 'engine.log')) ? fs.readFileSync(path.join(directory, 'engine.log'), 'utf8') : '');
const permitted = /ERROR: Failed to read the root certificate store\.\r?\n\s+at: get_system_ca_certificates \(platform\/windows\/os_windows\.cpp:2582\)/g;
const permittedEnvironmentWarnings = [...text.matchAll(permitted)].map(match => match[0]);
const noUnexpectedErrors = !/SCRIPT ERROR|ERROR:|leaked|still in use|crash/i.test(text.replace(permitted, ''));
const changedInputs = manifest.pins.filter(pin => hash(fs.readFileSync(path.join(manifest.project, pin.relative))) !== pin.sha256).map(pin => pin.relative);
const changedSourceTools = manifest.inputs.filter(pin => hash(fs.readFileSync(path.join(project, pin.relative))) !== pin.sha256).map(pin => pin.relative);
const success = result.status === 0 && native?.success === true && noUnexpectedErrors && changedInputs.length === 0 && changedSourceTools.length === 0;
const receipt = {success, directory, exitCode: result.status, error: result.error?.message ?? null, noUnexpectedErrors, permittedEnvironmentWarnings, changedInputs, changedSourceTools, native, gpu: false, serverConnections: 0};
fs.writeFileSync(path.join(directory, 'receipt.json'), JSON.stringify(receipt, null, 2), {flag: 'wx'});
console.log(JSON.stringify({...receipt, native: native ? {checks: native.checks, success: native.success, failures: native.failures, evidence: native.evidence, resources: native.resources?.length} : null}, null, 2));
process.exitCode = success ? 0 : 1;
