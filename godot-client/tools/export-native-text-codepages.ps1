param([string]$Destination=(Join-Path $PSScriptRoot '../data/native_text_codepages.json'))
$ErrorActionPreference='Stop'
# Export strict Windows code-page maps, not replacement/best-fit conversions.
# This is a development-time export; the client uses no process or OS codec.
Add-Type -TypeDefinition @'
using System;
using System.Text;
using System.Collections.Generic;
public static class NativeTextCodepages {
 public static object Export(int codepage) {
  var codec=Encoding.GetEncoding(codepage,EncoderFallback.ExceptionFallback,DecoderFallback.ExceptionFallback);
  var singles=new int[256];var pairs=new byte[131072];Array.Fill(pairs,(byte)255);
  var choices=new Dictionary<string,int>();var preferred=new Dictionary<string,int>();
  for(int i=0;i<256;i++) {
   singles[i]=-1;try {var s=codec.GetString(new byte[]{(byte)i});if(s.Length==1){singles[i]=s[0];choices[s]=i;}}catch(DecoderFallbackException){}
  }
  if(codepage!=1250 && codepage!=1252) for(int first=128;first<256;first++) for(int second=0;second<256;second++) {
   try {var s=codec.GetString(new byte[]{(byte)first,(byte)second});if(s.Length==1) {
    int key=(first<<8)|second; pairs[key*2]=(byte)s[0];pairs[key*2+1]=(byte)(s[0]>>8);
    choices.TryAdd(s,key);
   }}catch(DecoderFallbackException){}
  }
  foreach(var choice in choices) {
   try {var b=codec.GetBytes(choice.Key);int key=b.Length==1?b[0]:b.Length==2?(b[0]<<8)|b[1]:-1;
    if(key>=0 && codec.GetString(b)==choice.Key && key!=choice.Value)preferred[((int)choice.Key[0]).ToString()]=key;
   }catch(EncoderFallbackException){}
  }
  return new {codepage,single=singles,pairs=(codepage==1250||codepage==1252)?"":Convert.ToBase64String(pairs),preferred};
 }
}
'@
$tables=[ordered]@{}
foreach($codepage in @(1252,1250,949,950,936,932)){$tables[[string]$codepage]=[NativeTextCodepages]::Export($codepage)}
$document=[ordered]@{version=1;source='Strict System.Text.Encoding Windows code pages; generated by export-native-text-codepages.ps1';languageCodepages=[ordered]@{'0'=1252;'1'=1252;'2'=1252;'3'=1252;'4'=1252;'5'=1250;'128'=949;'129'=950;'130'=936;'131'=932};tables=$tables}
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Destination),($document|ConvertTo-Json -Depth 6 -Compress)+[Environment]::NewLine,[System.Text.UTF8Encoding]::new($false))
Get-Item -LiteralPath $Destination | Select-Object Name,Length
