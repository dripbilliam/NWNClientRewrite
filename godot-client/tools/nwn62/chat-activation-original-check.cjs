'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'../..');
const [engine,install,report]=process.argv.slice(2);
if(!engine||!install||!report)throw Error('Usage: node chat-activation-original-check.cjs <godot-console-exe> <original-install> <new-report-json>');
const output=path.resolve(report);
if(fs.existsSync(output)||fs.existsSync(output+'.fixture.json'))throw Error('Report path already exists');
fs.mkdirSync(path.dirname(output),{recursive:true});
const source='systems/native_chat_hud.gd';
const fixture='tests/native_chat_hud_test.gd';
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const argv=['--headless','--path',root,'--script',fixture,'--','--nwn62-chat-activation-phases',`--report=${output}.fixture.json`,`--install=${path.resolve(install)}`];
const run=spawnSync(path.resolve(engine),argv,{cwd:root,encoding:'utf8',maxBuffer:16*1024*1024,timeout:180000});
const log=(run.stdout??'')+(run.stderr??'');
fs.writeFileSync(output+'.log',log);
const prefix='NWN62_CHAT_ACTIVATION_PHASES ';
const phases=log.split(/\r?\n/).filter(line=>line.startsWith(prefix)).map(line=>JSON.parse(line.slice(prefix.length)));
const result={ticket:'NWN-62',scope:'Installed-original chat HUD fixture, opt-in phase counters; no FPS',engine:path.resolve(engine),engineSha256:sha(engine),sourceSha256:sha(path.join(root,source)),fixtureSha256:sha(path.join(root,fixture)),install:path.resolve(install),argv,exit:run.status,error:run.error?String(run.error):'',phases,fixtureReport:fs.existsSync(output+'.fixture.json')?JSON.parse(fs.readFileSync(output+'.fixture.json','utf8')):null};
fs.writeFileSync(output,JSON.stringify(result,null,2)+'\n');
if(run.status!==0||phases.length<1||!result.fixtureReport)throw Error('Original-content check failed: '+output);
console.log(JSON.stringify({report:output,exit:run.status,phaseRows:phases.length,phases}));
