import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
const root=process.cwd(), run=path.resolve(process.argv[2]??'');
const boundary=path.join(root,'godot-client','.cache','native-140fps','render-agent')+path.sep;
if(!run.startsWith(boundary)||fs.existsSync(run))throw Error('Fresh owned run directory required');
const descriptorPath=path.join(boundary,'engine-builtin-light-v2','engine-descriptor.json');
const descriptor=JSON.parse(fs.readFileSync(descriptorPath,'utf8'));
const engine=descriptor.engines.candidate;
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
if(!engine.sha256.startsWith('ce2d')||hash(engine.path)!==engine.sha256)throw Error('Engine pin mismatch');
const scripts=['tools/native_parity/visibility/mesh_provenance.gd','tools/native_parity/visibility/entity_visibility_trace.gd','tools/native_parity/visibility/terrain_pointer_trace.gd','tests/native_parity_visibility_trace_test.gd'];
const project=path.join(run,'project'),pins=[];
for(const relative of scripts){const source=path.join(root,'godot-client',relative),dest=path.join(project,relative);fs.mkdirSync(path.dirname(dest),{recursive:true});fs.copyFileSync(source,dest);pins.push({relative,sha256:hash(source)});}
fs.mkdirSync(path.join(project,'.godot'),{recursive:true});
fs.writeFileSync(path.join(project,'.godot','global_script_class_cache.cfg'),'list=[]\n');
fs.writeFileSync(path.join(project,'project.godot'),'[application]\nconfig/name="Isolated parity visibility fixture"\n\n[rendering]\nrenderer/rendering_method="gl_compatibility"\n');
fs.writeFileSync(path.join(run,'sources.json'),JSON.stringify({engine,descriptorPath,pins},null,2));
const args=['--headless','--path',project,'--script','res://tests/native_parity_visibility_trace_test.gd','--',`--report=${path.join(run,'checks.json')}`];
const begun=performance.now(),child=spawn(engine.path,args,{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
let out='',err='',timedOut=false,spawnError=null;
child.stdout.on('data',v=>out+=v);child.stderr.on('data',v=>err+=v);child.on('error',e=>spawnError=String(e));
const timer=setTimeout(()=>{timedOut=true;child.kill();},20000);
const closed=await new Promise(resolve=>child.once('close',(code,signal)=>resolve({code,signal})));
clearTimeout(timer);fs.writeFileSync(path.join(run,'stdout.log'),out);fs.writeFileSync(path.join(run,'stderr.log'),err);
const sourceChanged=pins.filter(p=>hash(path.join(root,'godot-client',p.relative))!==p.sha256).map(p=>p.relative);
const receipt={...closed,pid:child.pid,spawnError,timedOut,wall_ms:performance.now()-begun,engineSha256:engine.sha256,args,sourceChanged,scope:'Four-script synthetic headless correctness only; no original assets, connection, game area, GPU or FPS measurement'};
fs.writeFileSync(path.join(run,'process.json'),JSON.stringify(receipt,null,2));
console.log(JSON.stringify(receipt));console.log(out);console.log(err);process.exitCode=closed.code??1;
